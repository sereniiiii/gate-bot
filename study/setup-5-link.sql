-- ============================================================
--  同一件事的两个说法：把「大任务的一步」和「书的一章」绑在一起
--  用法：Supabase 后台 → SQL Editor → New query → 全选粘贴 → Run
--  可重复执行
--
--  做的事：给 subtasks 加一列 link_id，指向**另一条 subtasks 行**。
--  两条互相指着 = 同一件事的两种说法（「第 3 步」就是「第 3 章」）。
--  在任意一边勾完成，另一边自动跟着变 —— 书那边的章节进度条和大任务
--  这边的步骤进度条一起动。
--
--  为什么不是「一条行同时挂两个父」（去掉 setup-4 的异或约束）：
--  绑之前两步/两章已经各自存在了，合并就得删掉其中一行 —— 那是删她的数据。
--  用一列做「互相指」既不用删，也能随时解开。
--
--  跑之前页面照样能用，只是没法绑（「↔ 不绑」那一格选了会提示来跑这个脚本）。
-- ============================================================

-- 1. 指向对家那一行。不设外键约束：删除时由前端负责把对家的 link_id 松开，
--    设了 on delete set null 反而会在批量删除时产生大量级联写。
alter table public.subtasks add column if not exists link_id uuid;

-- 2. 反查「谁指着我」会走这个索引（refresh 之后前端在内存里查，这里主要是给人工排查用）
create index if not exists subtasks_link_id_idx on public.subtasks (link_id);


-- ============================================================
--  自检：应该出现 1 行
-- ============================================================
select table_name as 表名, column_name as 列名, data_type as 类型
from information_schema.columns
where table_schema = 'public' and table_name = 'subtasks' and column_name = 'link_id';


